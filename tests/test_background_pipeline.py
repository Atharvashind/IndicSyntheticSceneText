def test_background_composition_maps_unicode_text_and_bbox_to_verified_surface(tmp_path):
    source_path = tmp_path / "assets" / "backgrounds" / "test-fixture.png"
    asset = _make_background(tmp_path)
    original_bytes = source_path.read_bytes()
    scene, annotation, board = _compose_asset(asset)
    assert scene.size == (1600, 1200)
    assert board.size == tuple(annotation["background_composition"]["board_size"])
    assert annotation["language"] == "hindi"
    assert annotation["category"] == "shop_board"
    assert annotation["text_regions"][0]["transcription"]
    assert annotation["background_composition"]["source_type"] == "test_fixture"
    assert annotation["background_composition"]["homography_coordinate_system"] == "pixel_edges"
    assert source_path.read_bytes() == original_bytes
    assert validate_background_composition(annotation) == []
    assert validate_rendered_geometry(annotation) == []
    for region in annotation["text_regions"]:
        polygon = region["polygon"]
        bbox = region["bbox"]
        assert bbox == {
            "x_min": min(point[0] for point in polygon),
            "y_min": min(point[1] for point in polygon),
            "x_max": max(point[0] for point in polygon),
            "y_max": max(point[1] for point in polygon),
        }
        assert all(0 <= x <= scene.width and 0 <= y <= scene.height for x, y in polygon)


def test_background_composition_is_reproducible(tmp_path):
    first_scene, first_annotation, first_board = _compose(tmp_path)
    second_scene, second_annotation, second_board = _compose(tmp_path)
    assert ImageChops.difference(first_scene, second_scene).getbbox() is None
    assert ImageChops.difference(first_board, second_board).getbbox() is None
    assert first_annotation == second_annotation


