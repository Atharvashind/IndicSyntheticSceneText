COORDINATE_CONVENTION = (
    "pixel_edges; top-left origin; x right; y down; polygon order "
    "top-left, top-right, bottom-right, bottom-left"
)


def _make_background(tmp_path):
    path = tmp_path / "assets" / "backgrounds" / "test-fixture.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    background = Image.new("RGB", (1600, 1200), (185, 164, 132))
    draw = ImageDraw.Draw(background)
    draw.rectangle((0, 560, 1599, 1199), fill=(75, 91, 94))
    polygon = [[250, 140], [1350, 165], [1330, 500], [270, 480]]
    draw.polygon(polygon, fill=(239, 230, 202), outline=(55, 53, 48), width=12)
    background.save(path, format="PNG")
    record = {
        "background_id": "test-fixture-001",
        "asset_id": "test-fixture-001",
        "relative_path": "assets/backgrounds/test-fixture.png",
        "original_filename": "test-fixture.png",
        "source_type": "test_fixture",
        "scene_category": "shopfront",
        "image_width": 1600,
        "image_height": 1200,
        "provenance": "Generated by this test with Pillow; not a photograph or AI-service output.",
        "licensing": {
            "terms": "Test-only local fixture; not distributed.",
            "verification_status": "verified",
            "research_use_allowed": True,
            "redistribution_allowed": False,
            "evidence": "Created in a temporary test directory.",
        },
        "generation_prompt": None,
        "created_date": None,
        "signboard_surface_polygon": polygon,
        "surface_verification_status": "verified",
        "manual_review_status": "approved",
        "validation_warnings": [],
    }
    return BackgroundAsset(record, path)


def _compose_asset(asset):
    return compose_background_scene(
        asset,
        language="hindi",
        sample_seed=20261029,
        sample_id="background-smoke-001",
        board_seed=20261030,
        layout_id="centered_business_subtitle",
        layer_relative_path="board_layers/background-smoke-001_board.png",
        minimum_surface_width=360,
        minimum_surface_height=120,
    )


def _compose(tmp_path):
    return _compose_asset(_make_background(tmp_path))


def test_background_image_loader_validates_integrity_and_dimensions(tmp_path):
    asset = _make_background(tmp_path)
    loaded = load_background_image(asset.path, (1600, 1200))
    assert loaded.size == (1600, 1200)
    try:
        load_background_image(asset.path, (1200, 1600))
    except ValueError as error:
        assert "do not match manifest dimensions" in str(error)
    else:
        raise AssertionError("Mismatched dimensions were accepted.")
    with pytest.raises(ValueError, match="Cannot read background image"):
        load_background_image(tmp_path / "missing.png")


def test_manifest_excludes_unverified_provenance_and_unsupported_sources(tmp_path):
    asset = _make_background(tmp_path)
    record = copy.deepcopy(asset.record)
    record["licensing"]["verification_status"] = "unverified"
    record["manual_review_status"] = "pending"
    manifest_path = tmp_path / "assets" / "backgrounds" / "manifest.json"
    manifest_path.write_text(
        json.dumps(
            {"schema_version": "1.0", "coordinate_convention": COORDINATE_CONVENTION, "assets": [record]},
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    manifest = load_background_manifest(manifest_path, project_root=tmp_path)
    assert manifest.assets == ()
    assert any("license has not been verified" in reason for reason in manifest.excluded[0]["exclusion_reasons"])
    assert any("manual review is not approved" in reason for reason in manifest.excluded[0]["exclusion_reasons"])


