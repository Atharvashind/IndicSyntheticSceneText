def test_composition_and_all_existing_profiles_replay_surface_geometry(tmp_path):
    scene, parent, _ = _compose(tmp_path)
    original_text = [region["transcription"] for region in parent["text_regions"]]
    for profile in PROFILE_NAMES:
        seeded_parent = copy.deepcopy(parent)
        seeded_parent["random_seed"] = 717
        final_image, annotation = apply_profile(scene, seeded_parent, profile, 717)
        update_composed_surface_for_transform(annotation)
        assert [region["transcription"] for region in annotation["text_regions"]] == original_text
        assert validate_transformed_geometry(seeded_parent, annotation) == []
        assert validate_background_composition(annotation) == []
        assert validate_transformed_surface(seeded_parent, annotation) == []
        assert final_image.size == (annotation["image_width"], annotation["image_height"])


def test_background_transformed_dataset_passes_validator(tmp_path):
    scene, parent, board = _compose(tmp_path)
    root = tmp_path / "dataset" / "D2_perspective"
    image_dir = root / "images"
    annotation_dir = root / "annotations"
    parent_id = "background-smoke-001__base"
    parent["sample_id"] = parent_id
    parent["image"] = f"{parent_id}.png"
    parent_image_path = image_dir / "parents" / parent["image"]
    parent_annotation_path = annotation_dir / "parents" / f"{parent_id}.json"
    parent_image_path.parent.mkdir(parents=True)
    parent_annotation_path.parent.mkdir(parents=True)
    scene.save(parent_image_path, format="PNG")
    parent["validation"]["status"] = "passed"
    write_annotation(parent, parent_annotation_path)
    board_path = image_dir / parent["board_layer"]
    board_path.parent.mkdir(parents=True)
    board.save(board_path, format="PNG")

    sample_id = "background-smoke-001"
    source = copy.deepcopy(parent)
    source["sample_id"] = sample_id
    source["image"] = f"{sample_id}.png"
    source["parent"] = {
        "sample_id": parent_id,
        "image": f"parents/{parent_id}.png",
        "annotation": f"parents/{parent_id}.json",
    }
    source["random_seed"] = 1212
    final_image, annotation = apply_profile(scene, source, "D2_perspective", 1212)
    update_composed_surface_for_transform(annotation)
    annotation["validation"]["status"] = "passed"
    image_dir.mkdir(parents=True, exist_ok=True)
    annotation_dir.mkdir(parents=True, exist_ok=True)
    final_image_path = image_dir / annotation["image"]
    final_image.save(final_image_path, format="PNG")
    assert validate_annotation(annotation, final_image_path) == []
    write_annotation(annotation, annotation_dir / f"{sample_id}.json")

    report = validate_dataset(image_dir, annotation_dir)
    assert report["passed"] is True, report["errors"]
    assert report["image_count"] == report["annotation_count"] == 1
    assert report["background_source_counts"] == {"test_fixture": 1}
    assert report["difficulty_profile_counts"] == {"D2_perspective": 1}


def test_empty_manifest_generates_shortfall_report_without_claiming_completion(tmp_path):
    manifest_path = tmp_path / "manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "schema_version": "1.0",
                "coordinate_convention": COORDINATE_CONVENTION,
                "assets": [],
            }
        ),
        encoding="utf-8",
    )
    preview_root = tmp_path / "previews"
    report = generate_background_pilot(
        manifest_path,
        tmp_path / "data",
        preview_root,
        seed=993,
        project_root=tmp_path,
    )
    assert report["eligible_background_count"] == 0
    assert report["generated_scene_count"] == 0
    assert report["complete"] is False
    assert report["validation_applicable"] is False
    assert report["validation_passed"] is None
    assert report["shortfall"] == 24
    assert report["coverage"] == {
        "language_counts": {},
        "scene_category_counts": {},
        "source_type_counts": {},
        "difficulty_profile_counts": {},
    }
    for profile in PROFILE_NAMES:
        assert (preview_root / f"{profile}_contact_sheet.png").is_file()
    assert (preview_root / "pilot_manifest.json").is_file()
    assert (preview_root / "validation_report.json").is_file()
    assert (preview_root / "generation_report.json").is_file()


def test_pilot_generates_reproducible_smoke_scene_from_prevalidated_fixture(tmp_path, monkeypatch):
    asset = _make_background(tmp_path)
    original_bytes = asset.path.read_bytes()
    prevalidated = BackgroundManifest(
        manifest_path=tmp_path / "manifest.json",
        assets=(asset,),
        excluded=(),
        warnings=(),
    )
    monkeypatch.setattr(
        "src.background_pilot.load_background_manifest",
        Mock(return_value=prevalidated),
    )
    first_root = tmp_path / "first"
    second_root = tmp_path / "second"
    first = generate_background_pilot(
        prevalidated.manifest_path,
        first_root / "data",
        first_root / "previews",
        seed=4567,
        project_root=tmp_path,
    )
    second = generate_background_pilot(
        prevalidated.manifest_path,
        second_root / "data",
        second_root / "previews",
        seed=4567,
        project_root=tmp_path,
    )
    assert first["generated_scene_count"] == 1
    assert first["validation_applicable"] is True
    assert first["validation_passed"] is True
    assert first["complete"] is False
    assert first["coverage"] == second["coverage"]
    assert len(first["validation_reports"]) == len(PROFILE_NAMES)
    first_scene = json.loads((first_root / "previews" / "pilot_manifest.json").read_text(encoding="utf-8"))["scenes"][0]
    profile = first_scene["difficulty_profile"]
    sample_id = first_scene["sample_id"]
    first_image = first_root / "data" / profile / "images" / f"{sample_id}.png"
    second_image = second_root / "data" / profile / "images" / f"{sample_id}.png"
    first_annotation = first_root / "data" / profile / "annotations" / f"{sample_id}.json"
    second_annotation = second_root / "data" / profile / "annotations" / f"{sample_id}.json"
    assert first_image.read_bytes() == second_image.read_bytes()
    assert first_annotation.read_bytes() == second_annotation.read_bytes()
    assert asset.path.read_bytes() == original_bytes
