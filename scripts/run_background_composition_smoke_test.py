import argparse
import copy
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT_DIR = Path(__file__).resolve().parents[1]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src.annotation_exporter import (
    validate_annotation,
    validate_rendered_geometry,
    validate_transformed_geometry,
    write_annotation,
)
from src.background_assets import BackgroundAsset
from src.background_composer import (
    compose_background_scene,
    update_composed_surface_for_transform,
    validate_background_composition,
    validate_transformed_surface,
)
from src.content_engine import load_config
from src.scene_transformer import apply_profile


def _draw_overlay(image: Image.Image, annotation: dict, output_path: Path) -> None:
    overlay = image.convert("RGB").copy()
    draw = ImageDraw.Draw(overlay)
    for region in annotation["text_regions"]:
        polygon = [(round(x), round(y)) for x, y in region["polygon"]]
        draw.line(polygon + [polygon[0]], fill=(255, 0, 0), width=3)
    overlay.save(output_path, format="PNG")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Smoke-test background composition with a clearly labeled local test fixture."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT_DIR / "previews" / "background_composition_smoke_test_seed_20261029",
    )
    arguments = parser.parse_args()
    output = arguments.output
    expected_files = (
        "test_background.png",
        "board_layer.png",
        "composed_scene.png",
        "composed_scene_annotation.json",
        "perspective_scene.png",
        "perspective_scene_annotation.json",
        "perspective_overlay.png",
        "validation_report.json",
    )
    existing = [output / name for name in expected_files if (output / name).exists()]
    if existing:
        raise FileExistsError(
            "Refusing to overwrite smoke-test outputs: "
            + ", ".join(str(path) for path in existing)
        )
    output.mkdir(parents=True, exist_ok=True)

    background_path = output / "test_background.png"
    background = Image.new("RGB", (1600, 1200), (185, 164, 132))
    draw = ImageDraw.Draw(background)
    draw.rectangle((0, 560, 1599, 1199), fill=(75, 91, 94))
    surface = [[250, 140], [1350, 165], [1330, 500], [270, 480]]
    draw.polygon(surface, fill=(239, 230, 202), outline=(55, 53, 48), width=12)
    background.save(background_path, format="PNG")
    original_bytes = background_path.read_bytes()

    record = {
        "background_id": "smoke-test-fixture",
        "asset_id": "smoke-test-fixture",
        "relative_path": "test_background.png",
        "original_filename": "test_background.png",
        "source_type": "test_fixture",
        "scene_category": "shopfront",
        "image_width": 1600,
        "image_height": 1200,
        "provenance": "Generated by this smoke-test script with Pillow; not a photograph or AI-service output.",
        "licensing": {
            "terms": "Local test artwork created by this script; not redistributed.",
            "verification_status": "verified",
            "research_use_allowed": True,
            "redistribution_allowed": False,
            "evidence": "Created locally by the smoke-test script.",
        },
        "generation_prompt": None,
        "created_date": None,
        "signboard_surface_polygon": surface,
        "surface_verification_status": "verified",
        "manual_review_status": "approved",
        "validation_warnings": [],
    }
    config = load_config()
    scene, base, board = compose_background_scene(
        BackgroundAsset(record, background_path),
        language="marathi",
        sample_seed=20261029,
        sample_id="background-smoke-20261029",
        board_seed=20261030,
        layout_id="centered_business_subtitle",
        layer_relative_path="board_layer.png",
        minimum_surface_width=config["background_pipeline"]["minimum_surface_width"],
        minimum_surface_height=config["background_pipeline"]["minimum_surface_height"],
    )
    base["image"] = "composed_scene.png"
    base["validation"]["status"] = "passed"
    scene_path = output / base["image"]
    scene.save(scene_path, format="PNG")
    board.save(output / "board_layer.png", format="PNG")
    errors = validate_annotation(base, scene_path)
    errors.extend(validate_rendered_geometry(base))
    errors.extend(validate_background_composition(base))
    if errors:
        raise ValueError("Base composition failed validation: " + "; ".join(errors))
    write_annotation(base, output / "composed_scene_annotation.json")

    variant_seed = 20261031
    variant_input = copy.deepcopy(base)
    variant_input["sample_id"] = "background-smoke-20261029-perspective"
    variant_input["image"] = "perspective_scene.png"
    variant_input["random_seed"] = variant_seed
    variant_input["parent"] = {
        "sample_id": base["sample_id"],
        "image": "composed_scene.png",
        "annotation": "composed_scene_annotation.json",
    }
    transformed, variant = apply_profile(
        scene,
        variant_input,
        "D2_perspective",
        variant_seed,
        config,
    )
    update_composed_surface_for_transform(variant)
    variant["validation"]["status"] = "passed"
    variant_path = output / variant["image"]
    transformed.save(variant_path, format="PNG")
    errors = validate_annotation(variant, variant_path)
    errors.extend(validate_rendered_geometry(variant))
    errors.extend(validate_transformed_geometry(base, variant))
    errors.extend(validate_background_composition(variant))
    errors.extend(validate_transformed_surface(base, variant))
    if errors:
        raise ValueError("Perspective composition failed validation: " + "; ".join(errors))
    write_annotation(variant, output / "perspective_scene_annotation.json")
    _draw_overlay(transformed, variant, output / "perspective_overlay.png")

    if background_path.read_bytes() != original_bytes:
        raise RuntimeError("The original test background changed during composition.")
    report = {
        "fixture_type": "procedural_test_fixture",
        "not_a_real_photo_or_ai_generated_image": True,
        "base_composition_validation": "passed",
        "perspective_geometry_validation": "passed",
        "source_background_unchanged": True,
        "manual_visual_review_required": True,
        "output_directory": str(output),
    }
    (output / "validation_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
